#!/usr/bin/env node
/**
 * Generate the aggregator's catalog sections for the docs indexes and the
 * identity editor's preview panes.
 *
 * catalog-aggregate.json is the official catalog: its `sections` are the
 * groupings every surface should follow, so the section paths, labels and item
 * order come straight from it. Any manifest the aggregate does not place is
 * reported and left out — the indexes stay faithful to the aggregate rather
 * than inventing a section.
 *
 * Writes apps/web/content/catalog-sections.generated.ts.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const aggregate = JSON.parse(readFileSync(join(root, "catalog-aggregate.json"), "utf8"));
const outFile = join(root, "apps/web/content/catalog-sections.generated.ts");

const componentNames = new Set(
  readdirSync(join(root, "packages/foundation/src/manifests"))
    .filter((file) => file.endsWith(".manifest.json"))
    .map((file) => file.replace(".manifest.json", "")),
);
const blockNames = new Set(
  readdirSync(join(root, "packages/foundation/src/blocks"))
    .filter((file) => file.endsWith(".block.json"))
    .map((file) => file.replace(".block.json", "")),
);

const slugOf = (item) => item.registry?.name ?? item.name.toLowerCase().replaceAll(" ", "-");

/**
 * "Marketing blocks / Hero" -> group "Marketing blocks", label "Hero".
 * "Application blocks / 7Ovr Free application blocks / Activity" ->
 * group "Application blocks", label "7Ovr Free · Activity".
 */
function splitSection(section) {
  const parts = section.split(" / ");
  if (parts.length === 1) return { group: "", label: parts[0] };
  const [group, ...rest] = parts;
  const label =
    rest.length === 1
      ? rest[0]
      : rest
          .map((part, index) =>
            index === rest.length - 1 ? part : part.replace(/ application blocks$/, ""),
          )
          .join(" · ");
  return { group, label };
}

function collect(topSection, known, kind) {
  const sections = [];
  const placed = new Set();
  const seen = new Set();
  for (const [section, items] of Object.entries(aggregate.sections[topSection] ?? {})) {
    const names = [];
    for (const item of items) {
      const slug = slugOf(item);
      // Duplicate aggregate entries (grid-pattern ships twice): first wins.
      if (seen.has(slug)) continue;
      seen.add(slug);
      if (!known.has(slug)) {
        console.warn(`${kind}: ${slug} listed in "${section}" has no ${kind} file — skipped`);
        continue;
      }
      names.push(slug);
      placed.add(slug);
    }
    if (names.length === 0) continue;
    const { group, label } = splitSection(section);
    sections.push({ key: section, group, label, items: names });
  }
  for (const name of known) {
    if (!placed.has(name)) console.warn(`${kind}: ${name} is not in catalog-aggregate.json — skipped`);
  }
  return sections;
}

const componentSections = collect("Components", componentNames, "component");
const blockSections = collect("Blocks", blockNames, "block");

const byName = (sections) => {
  const map = {};
  for (const section of sections) for (const name of section.items) map[name] = section.key;
  return map;
};

const literal = (sections) =>
  `[\n${sections
    .map(
      (section) =>
        `  {\n    key: ${JSON.stringify(section.key)},\n    group: ${JSON.stringify(section.group)},\n    label: ${JSON.stringify(section.label)},\n    items: ${JSON.stringify(section.items)},\n  },`,
    )
    .join("\n")}\n]`;

const mapLiteral = (map) =>
  `{\n${Object.entries(map)
    .map(([name, key]) => `  ${JSON.stringify(name)}: ${JSON.stringify(key)},`)
    .join("\n")}\n}`;

const source = `// Generated by scripts/generate-catalog-sections.mjs — do not edit by hand.
// Run: node scripts/generate-catalog-sections.mjs

export interface CatalogSection {
  /** The aggregator's section path, e.g. "Application blocks / Sidebar". */
  key: string;
  /** Top-level aggregator section; empty for components. */
  group: string;
  /** Display label, e.g. "blocks.so · Sidebar". */
  label: string;
  /** Manifest names, in aggregator order. */
  items: string[];
}

export const COMPONENT_SECTIONS: CatalogSection[] = ${literal(componentSections)};

export const BLOCK_SECTIONS: CatalogSection[] = ${literal(blockSections)};

/** Component manifest name -> aggregator section key. */
export const COMPONENT_SECTION_BY_NAME: Record<string, string> = ${mapLiteral(byName(componentSections))};

/** Block manifest name -> aggregator section key. */
export const BLOCK_SECTION_BY_NAME: Record<string, string> = ${mapLiteral(byName(blockSections))};
`;

writeFileSync(outFile, source);
console.log(
  `catalog sections: ${componentSections.length} component sections, ${blockSections.length} block sections -> ${outFile}`,
);
